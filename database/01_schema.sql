-- =====================================================================
-- AdLedger – Campaign-to-Revenue Intelligence Platform
-- 01_schema.sql : database, tables, keys and constraints (MySQL 8.0.16+)
--
-- Note: LEAD is a reserved word in MySQL 8 (window function), so the
-- table name `lead` must always be written inside backticks.
-- =====================================================================

DROP DATABASE IF EXISTS adledger_db;
CREATE DATABASE adledger_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE adledger_db;

-- ---------------------------------------------------------------------
-- Agency_User : staff who log in to the system
-- ---------------------------------------------------------------------
CREATE TABLE agency_user (
    user_id        INT AUTO_INCREMENT PRIMARY KEY,
    full_name      VARCHAR(100) NOT NULL,
    email          VARCHAR(120) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    role           ENUM('Admin', 'Manager', 'Sales') NOT NULL DEFAULT 'Sales',
    created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------
-- Client : companies the agency works for
-- ---------------------------------------------------------------------
CREATE TABLE client (
    client_id       INT AUTO_INCREMENT PRIMARY KEY,
    company_name    VARCHAR(120) NOT NULL UNIQUE,
    contact_person  VARCHAR(100),
    email           VARCHAR(120) NOT NULL,
    phone           VARCHAR(20),
    industry        VARCHAR(60),
    status          ENUM('Active', 'Inactive') NOT NULL DEFAULT 'Active'
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------
-- Campaign : one client has many campaigns
-- ---------------------------------------------------------------------
CREATE TABLE campaign (
    campaign_id    INT AUTO_INCREMENT PRIMARY KEY,
    client_id      INT NOT NULL,
    campaign_name  VARCHAR(120) NOT NULL,
    platform       VARCHAR(30) NOT NULL,
    objective      ENUM('Awareness', 'Leads', 'Conversions', 'Sales') NOT NULL DEFAULT 'Leads',
    start_date     DATE NOT NULL,
    end_date       DATE,
    budget         DECIMAL(12, 2) NOT NULL,
    status         ENUM('Active', 'Paused', 'Completed') NOT NULL DEFAULT 'Active',
    CONSTRAINT fk_campaign_client FOREIGN KEY (client_id)
        REFERENCES client (client_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_campaign_budget CHECK (budget >= 0),
    CONSTRAINT chk_campaign_dates  CHECK (end_date IS NULL OR end_date >= start_date)
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------
-- Ad_Spend : daily spend per campaign
-- ---------------------------------------------------------------------
CREATE TABLE ad_spend (
    spend_id     INT AUTO_INCREMENT PRIMARY KEY,
    campaign_id  INT NOT NULL,
    spend_date   DATE NOT NULL,
    amount       DECIMAL(12, 2) NOT NULL,
    impressions  INT NOT NULL DEFAULT 0,
    clicks       INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_spend_campaign FOREIGN KEY (campaign_id)
        REFERENCES campaign (campaign_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT uq_spend_campaign_day UNIQUE (campaign_id, spend_date),
    CONSTRAINT chk_spend_amount CHECK (amount >= 0),
    CONSTRAINT chk_spend_counts CHECK (impressions >= 0 AND clicks >= 0 AND clicks <= impressions)
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------
-- Lead : prospects generated by a campaign
-- ---------------------------------------------------------------------
CREATE TABLE `lead` (
    lead_id      INT AUTO_INCREMENT PRIMARY KEY,
    campaign_id  INT NOT NULL,
    lead_name    VARCHAR(100) NOT NULL,
    email        VARCHAR(120),
    phone        VARCHAR(20),
    source       VARCHAR(50),
    lead_date    DATE NOT NULL,
    status       ENUM('New', 'Contacted', 'Converted', 'Lost') NOT NULL DEFAULT 'New',
    CONSTRAINT fk_lead_campaign FOREIGN KEY (campaign_id)
        REFERENCES campaign (campaign_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_lead_contact CHECK (email IS NOT NULL OR phone IS NOT NULL)
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------
-- Lead_Followup : contact attempts made by a user to a lead
-- ---------------------------------------------------------------------
CREATE TABLE lead_followup (
    followup_id    INT AUTO_INCREMENT PRIMARY KEY,
    lead_id        INT NOT NULL,
    user_id        INT NOT NULL,
    followup_date  DATE NOT NULL,
    method         ENUM('Call', 'WhatsApp', 'Email', 'Meeting') NOT NULL DEFAULT 'Call',
    notes          TEXT,
    outcome        ENUM('Pending', 'Positive', 'Negative') NOT NULL DEFAULT 'Pending',
    CONSTRAINT fk_followup_lead FOREIGN KEY (lead_id)
        REFERENCES `lead` (lead_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_followup_user FOREIGN KEY (user_id)
        REFERENCES agency_user (user_id) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------
-- Sale : a lead may result in (at most) one sale
-- ---------------------------------------------------------------------
CREATE TABLE sale (
    sale_id          INT AUTO_INCREMENT PRIMARY KEY,
    lead_id          INT NOT NULL UNIQUE,
    sale_date        DATE NOT NULL,
    sale_amount      DECIMAL(12, 2) NOT NULL,
    product_service  VARCHAR(120),
    CONSTRAINT fk_sale_lead FOREIGN KEY (lead_id)
        REFERENCES `lead` (lead_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_sale_amount CHECK (sale_amount > 0)
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------
-- Invoice : billed to a client; status is maintained by triggers
-- ---------------------------------------------------------------------
CREATE TABLE invoice (
    invoice_id    INT AUTO_INCREMENT PRIMARY KEY,
    client_id     INT NOT NULL,
    issue_date    DATE NOT NULL,
    due_date      DATE NOT NULL,
    total_amount  DECIMAL(12, 2) NOT NULL,
    status        ENUM('Unpaid', 'Partial', 'Paid', 'Overdue') NOT NULL DEFAULT 'Unpaid',
    CONSTRAINT fk_invoice_client FOREIGN KEY (client_id)
        REFERENCES client (client_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_invoice_amount CHECK (total_amount > 0),
    CONSTRAINT chk_invoice_dates  CHECK (due_date >= issue_date)
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------
-- Payment : one invoice can be paid in several parts
-- ---------------------------------------------------------------------
CREATE TABLE payment (
    payment_id      INT AUTO_INCREMENT PRIMARY KEY,
    invoice_id      INT NOT NULL,
    payment_date    DATE NOT NULL,
    amount          DECIMAL(12, 2) NOT NULL,
    payment_method  ENUM('Bank Transfer', 'Cash', 'Cheque', 'Card') NOT NULL DEFAULT 'Bank Transfer',
    CONSTRAINT fk_payment_invoice FOREIGN KEY (invoice_id)
        REFERENCES invoice (invoice_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT chk_payment_amount CHECK (amount > 0)
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------
-- Deliverable : work items owed for a campaign, assigned to a user
-- ---------------------------------------------------------------------
CREATE TABLE deliverable (
    deliverable_id  INT AUTO_INCREMENT PRIMARY KEY,
    campaign_id     INT NOT NULL,
    user_id         INT NOT NULL,
    title           VARCHAR(150) NOT NULL,
    due_date        DATE,
    status          ENUM('Pending', 'In Progress', 'Done') NOT NULL DEFAULT 'Pending',
    CONSTRAINT fk_deliverable_campaign FOREIGN KEY (campaign_id)
        REFERENCES campaign (campaign_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_deliverable_user FOREIGN KEY (user_id)
        REFERENCES agency_user (user_id) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------
-- Lead_Status_Log : audit trail, filled only by trg_lead_status_log
-- ---------------------------------------------------------------------
CREATE TABLE lead_status_log (
    log_id      INT AUTO_INCREMENT PRIMARY KEY,
    lead_id     INT NOT NULL,
    old_status  VARCHAR(20),
    new_status  VARCHAR(20) NOT NULL,
    changed_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_log_lead FOREIGN KEY (lead_id)
        REFERENCES `lead` (lead_id) ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------
-- Indexes on columns used for joins / filters in reports
-- (InnoDB already indexes PK, UNIQUE and FK columns)
-- ---------------------------------------------------------------------
CREATE INDEX idx_lead_status     ON `lead` (status);
CREATE INDEX idx_lead_date       ON `lead` (lead_date);
CREATE INDEX idx_sale_date       ON sale (sale_date);
CREATE INDEX idx_invoice_status  ON invoice (status);
CREATE INDEX idx_campaign_status ON campaign (status);
